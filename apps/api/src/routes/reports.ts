import { Router } from 'express';
import { prisma } from '../lib/prisma.js';
import { param } from '../lib/http.js';
import { forbidden, notFound } from '../lib/errors.js';
import { isoDate } from '../lib/dates.js';
import { ctxOf } from '../middleware/auth.js';
import { accessibleProjectIds, assertCan, assertProjectAccess, can } from '../services/access.js';
import { audit } from '../services/audit.js';
import { findReport, parseRange, reportCatalog } from '../services/reports.js';
import { toCsv, toPdf, toXlsx } from '../services/exporter.js';
import { portfolio, projectDashboard, projectOperations } from '../services/dashboard.js';

export const reportsRouter = Router({ mergeParams: true });
export const portfolioRouter = Router();

reportsRouter.use(async (req, _res, next) => {
  await assertProjectAccess(prisma, ctxOf(req), param(req, 'projectId'));
  next();
});

reportsRouter.get('/dashboard', async (req, res) => {
  const ctx = ctxOf(req);
  const projectId = param(req, 'projectId');
  assertCan(ctx, 'project.view', projectId);
  const { from, to } = parseRange(req.query.from, req.query.to);
  res.json(await projectDashboard(prisma, projectId, { from, to, userId: ctx.user.id }));
});

reportsRouter.get('/dashboard/operations', async (req, res) => {
  const ctx = ctxOf(req);
  const projectId = param(req, 'projectId');
  assertCan(ctx, 'project.view', projectId);
  res.json(await projectOperations(prisma, projectId));
});

reportsRouter.get('/reports', async (req, res) => {
  const ctx = ctxOf(req);
  const projectId = param(req, 'projectId');
  assertCan(ctx, 'report.view', projectId);
  res.json({ reports: reportCatalog(ctx, projectId), canExport: can(ctx, 'report.export', projectId) });
});

reportsRouter.get('/reports/:key', async (req, res) => {
  const ctx = ctxOf(req);
  const projectId = param(req, 'projectId');
  assertCan(ctx, 'report.view', projectId);
  const def = findReport(param(req, 'key'));
  if (!def) throw notFound('Report');
  if (!can(ctx, def.permission, projectId)) throw forbidden(`This report requires ${def.permission}`);
  const range = parseRange(req.query.from, req.query.to);
  const result = await def.run({ projectId, ...range }, ctx);
  const format = typeof req.query.format === 'string' ? req.query.format : 'json';
  if (format === 'json') return res.json({ key: def.key, title: def.title, group: def.group, ...result });
  if (!can(ctx, 'report.export', projectId)) throw forbidden('Exporting reports requires report.export');
  const project = await prisma.project.findUniqueOrThrow({ where: { id: projectId } });
  const meta: Array<[string, string]> = [
    ['Project', `${project.code} — ${project.name}`],
    ['Period', range.from || range.to ? `${isoDate(range.from) ?? 'start'} to ${isoDate(range.to) ?? 'today'}` : 'All dates'],
    ['Generated by', ctx.user.name],
    ['Generated at', new Date().toISOString().slice(0, 16).replace('T', ' ') + ' UTC'],
  ];
  if (project.isDemo) meta.push(['Data', 'DEMO DATA — not real project figures']);
  const fileBase = `${project.code}-${def.key}-${isoDate(new Date())}`;
  await audit(prisma, ctx, { action: 'REPORT_EXPORT', entityType: 'report', entityId: def.key, projectId, summary: `${def.title} exported as ${format}` });
  if (format === 'csv') {
    res.setHeader('Content-Type', 'text/csv; charset=utf-8');
    res.setHeader('Content-Disposition', `attachment; filename="${fileBase}.csv"`);
    return res.send(toCsv(result));
  }
  if (format === 'xlsx') {
    res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
    res.setHeader('Content-Disposition', `attachment; filename="${fileBase}.xlsx"`);
    return res.send(await toXlsx(def.title, meta, result));
  }
  if (format === 'pdf') {
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="${fileBase}.pdf"`);
    return res.send(await toPdf(def.title, `${project.code} — ${project.name}`, meta, result, project.currency));
  }
  throw notFound('Format');
});

portfolioRouter.get('/', async (req, res) => {
  const ctx = ctxOf(req);
  const ids = (await accessibleProjectIds(prisma, ctx)).filter((id) => can(ctx, 'budget.view', id));
  res.json(await portfolio(prisma, ids));
});
